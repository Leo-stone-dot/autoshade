#!/usr/bin/env python3
"""Compile `resources/strings/*.toml` into the Rust resource accessors.

The TOML files are the SOURCE of the app's text (the Android/iOS model: one
file per locale, a stable key per string). This script compiles them into the
checked-in `src/text/generated.rs`: one `Key` constant per resource, the locale
tables in key order, the placeholder metadata and the rationale/value key
lists the producers name.

Determinism: the key order is the order of the `en.toml` tables and rows (the
English file is the default locale and therefore also the key registry). Keep
new rows appended; `scripts/check_text.py` fails if the generated module is
stale. Run: py -3 scripts/gen_text.py
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RESOURCES = REPO / "resources" / "strings"
GENERATED = REPO / "src" / "text" / "generated.rs"

DEFAULT = "en"
LOCALES = {"en": "EN", "zh-Hans": "ZH_HANS"}


def const_of(key: str) -> str:
    return "K_" + "".join(c if c.isalnum() else "_" for c in key).upper()


def alias_of(key: str) -> str:
    """The producer spelling inside `rationale_keys` (key `rationale.fit_x` ->
    `FIT_X`)."""
    return key.split(".", 1)[1].upper()


def load() -> tuple[list[tuple[str, str]], dict[str, list[str]]]:
    """[(key, group)] in default-file order, and {locale: texts in key order}."""
    tables: dict[str, dict[str, dict[str, str]]] = {}
    for locale in [DEFAULT, *[l for l in LOCALES if l != DEFAULT]]:
        path = RESOURCES / f"{locale}.toml"
        if not path.exists():
            sys.exit(f"missing resource file {path}")
        with path.open("rb") as fh:
            tables[locale] = tomllib.load(fh)

    keys: list[tuple[str, str]] = []
    for group, rows in tables[DEFAULT].items():
        for name in rows:
            keys.append((f"{group}.{name}", group))

    wanted = {k for k, _ in keys}
    for locale, table in tables.items():
        got = {f"{g}.{n}" for g, rows in table.items() for n in rows}
        if got != wanted:
            missing = sorted(wanted - got)
            extra = sorted(got - wanted)
            sys.exit(f"{locale}.toml key mismatch: missing={missing[:5]} extra={extra[:5]}")

    texts: dict[str, list[str]] = {}
    for locale, var in LOCALES.items():
        out: list[str] = []
        for key, group in keys:
            out.append(tables[locale][group][key[len(group) + 1 :]])
        texts[locale] = out
    return keys, texts


def placeholders(text: str) -> list[str]:
    import re

    return sorted(set(re.findall(r"\{([A-Za-z_][A-Za-z0-9_]*)\}", text)))


def rust_str(text: str) -> str:
    out = ['"']
    for c in text:
        if c == '"':
            out.append('\\"')
        elif c == "\\":
            out.append("\\\\")
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif c == "\r":
            out.append("\\r")
        elif ord(c) < 0x20:
            out.append(f"\\u{{{ord(c):04X}}}")
        else:
            out.append(c)
    out.append('"')
    return "".join(out)


def render(keys, texts) -> str:
    n = len(keys)
    en = texts["en"]
    zh = texts["zh-Hans"]
    out: list[str] = [
        "// Generated by scripts/gen_text.py from resources/strings/*.toml — do not edit.",
        "//",
        "// One `Key` per resource, the locale tables in key order, and the",
        "// placeholder metadata `scripts/check_text.py` and the tests read.",
        "",
        "/// One stable text resource id (Android's `R.string`, iOS's localized key).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]",
        "pub enum Key {",
        "    /// A resource row in the locale tables.",
        "    Resource(u16),",
        "    /// A NON-translatable literal (a number, an aspect ratio, a glyph): the",
        "    /// catalogue has no row for it, and `tr` returns it unchanged in every",
        "    /// locale — the old English fallback, made explicit.",
        "    Raw(&'static str),",
        "}",
        "",
    ]
    for index, (key, _group) in enumerate(keys):
        out.append(f"pub const {const_of(key)}: Key = Key::Resource({index});")
    out.append("")
    out.append("pub(crate) static EN: [&str; %d] = [" % n)
    out.extend(f"    {rust_str(text)}," for text in en)
    out.append("];")
    out.append("")
    out.append("pub(crate) static ZH_HANS: [&str; %d] = [" % n)
    out.extend(f"    {rust_str(text)}," for text in zh)
    out.append("];")
    out.append("")
    out.append("pub static NAMES: [&str; %d] = [" % n)
    out.extend(f'    "{key}",' for key, _ in keys)
    out.append("];")
    out.append("")
    out.append("pub static PLACEHOLDERS: [&[&str]; %d] = [" % n)
    for text in en:
        ph = ", ".join(f'"{p}"' for p in placeholders(text))
        out.append(f"    &[{ph}],")
    out.append("];")
    out.append("")

    rationale = [i for i, (key, _) in enumerate(keys) if key.startswith("rationale.")]
    values = [i for i, (key, _) in enumerate(keys) if key.startswith("value.")]
    out.append("/// Every rationale note template, in the default locale's order.")
    out.append(f"pub static RATIONALE_KEYS: [Key; {len(rationale)}] = [")
    out.extend(f"    Key::Resource({i})," for i in rationale)
    out.append("];")
    out.append("")
    out.append("/// The `rationale::values::ALL` key set, in `value.toml` order.")
    out.append(f"pub static VALUE_KEYS: [Key; {len(values)}] = [")
    out.extend(f"    Key::Resource({i})," for i in values)
    out.append("];")
    out.append("")
    out.append("/// The producers' spelling of the rationale template keys")
    out.append("/// (`rationale::keys` re-exports this module).")
    out.append("pub mod rationale_keys {")
    out.append("    use super::Key;")
    for i in rationale:
        key, _ = keys[i]
        out.append(f"    pub const {alias_of(key)}: Key = super::Key::Resource({i});")
    out.append("}")
    out.append("")

    return "\n".join(out)

def main() -> int:
    keys, texts = load()
    out = render(keys, texts)
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(out, encoding="utf-8")
    n = len(keys)
    rationale = sum(1 for key, _ in keys if key.startswith("rationale."))
    values = sum(1 for key, _ in keys if key.startswith("value."))
    print(f"wrote {GENERATED} ({n} resources: {rationale} rationale, {values} values)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
